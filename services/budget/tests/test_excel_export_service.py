    def test_tz_aware_confirmed_at_does_not_break_save(self):
        # openpyxl rejects tz-aware datetimes only at wb.save() time, not at cell-write
        # time — a bare ws.cell() assertion would miss this; must round-trip through save.
        budget = BudgetFactory.build(
            local_currency="GBP",
            actual_currency="USD",
            confirmed_at=datetime(2026, 1, 10, tzinfo=timezone.utc),
        )
        wb = Workbook()
        ws = wb.active
        DashboardSheet(ws, budget, "Org", "Donor", [], [], [], [], [], None, None).write()

        buf = io.BytesIO()
        wb.save(buf)
        reloaded = load_workbook(buf)["Sheet"]
        assert reloaded.cell(row=9, column=2).value == datetime(2026, 1, 10)


