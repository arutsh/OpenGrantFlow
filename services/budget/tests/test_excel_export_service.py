        assert ws.max_column == 5
        assert rows[8] == (
            "BUDGET SUMMARY", "Notes", "Vendor", "Amount (GBP)", "Donor Estimate"
        )
        assert rows[14] == ("Coordinator", "Approved", "Acme", 500, None)

