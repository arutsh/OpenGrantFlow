class TestComputeConvertedExpense:
    def test_fully_allocated_line_uses_only_real_rate_no_flag(self):
        rollup = BudgetLineExpenseRollup(
            budget_line_id=uuid4(),
            total_local_amount=100.0,
            allocations=[
                AllocationRollup(
                    amount_allocated=100.0,
                    conversion_donor_amount=50.0,
                    conversion_local_amount=100.0,
                )
            ],
        )

        result = _compute_converted_expense(rollup, estimated_exchange_rate=2.0)

        assert result.converted_donor_amount == 50.0
        assert result.is_estimated is False

    def test_partially_allocated_line_blends_real_and_estimated(self):
        rollup = BudgetLineExpenseRollup(
            budget_line_id=uuid4(),
            total_local_amount=100.0,
            allocations=[
                AllocationRollup(
                    amount_allocated=60.0,
                    conversion_donor_amount=30.0,
                    conversion_local_amount=60.0,
                )
            ],
        )

        result = _compute_converted_expense(rollup, estimated_exchange_rate=2.0)

        # 60 local -> 30 donor (real rate); remainder 40 local -> 20 donor (estimated rate)
        assert result.converted_donor_amount == 50.0
        assert result.is_estimated is True

    def test_fully_unallocated_line_is_fully_estimated(self):
        rollup = BudgetLineExpenseRollup(
            budget_line_id=uuid4(), total_local_amount=100.0, allocations=[]
        )

        result = _compute_converted_expense(rollup, estimated_exchange_rate=2.0)

        assert result.converted_donor_amount == 50.0
        assert result.is_estimated is True

    def test_zero_expense_line_is_not_flagged(self):
        rollup = BudgetLineExpenseRollup(
            budget_line_id=uuid4(), total_local_amount=0.0, allocations=[]
        )

        result = _compute_converted_expense(rollup, estimated_exchange_rate=2.0)

        assert result.converted_donor_amount == 0.0
        assert result.is_estimated is False


