        DashboardSheet(ws, budget, "Org", "Donor", [], [], [], [], {}, None, None).write()

        buf = io.BytesIO()
        wb.save(buf)
        reloaded = load_workbook(buf)["Sheet"]
        assert reloaded.cell(row=9, column=2).value == datetime(2026, 1, 10)


