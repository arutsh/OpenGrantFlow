async def _make_budget(db, owner_id=OWNER_ID, funding_customer_id=None):
    # Raw model, not BudgetFactory: setting its .budget relationship nulls the FK at flush.
    budget = BudgetModel(
        name="Test Budget",
        owner_id=owner_id,
        funding_customer_id=funding_customer_id,
        status=BudgetStatus.confirmed,
        start_date=date(2026, 1, 1),
        duration_months=12,
        local_currency="GBP",
        # tz-aware, matching the DateTime(timezone=True) column — catches openpyxl's
        # rejection of tz-aware datetimes, which only surfaces on an actual wb.save().
        confirmed_at=datetime(2026, 1, 5, tzinfo=timezone.utc),
    )
    db.add(budget)
    await db.commit()
    await db.refresh(budget)
    return budget


