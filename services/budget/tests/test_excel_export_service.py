    def test_full_layout_with_rate(self):
        budget = BudgetFactory.build(
            local_currency="GBP", actual_currency="USD", estimated_exchange_rate=2.0
        )
        cat1 = BudgetCategoryFactory.build(
            budget=budget, budget_id=budget.id, name="Personnel", created_at=datetime(2026, 1, 1)
        )
        cat2 = BudgetCategoryFactory.build(
            budget=budget, budget_id=budget.id, name="Travel", created_at=datetime(2026, 1, 2)
        )
        line1 = BudgetLineFactory.build(
            budget=budget,
            budget_id=budget.id,
            category=cat1,
            category_id=cat1.id,
            description="Salaries",
            amount=1000.0,
            created_at=datetime(2026, 1, 1),
        )
        line2 = BudgetLineFactory.build(
            budget=budget,
            budget_id=budget.id,
            category=cat2,
            category_id=cat2.id,
            description="Flights",
            amount=200.0,
            created_at=datetime(2026, 1, 2),
        )

        data = generate_budget_export_workbook(
            budget,
            [cat1, cat2],
            [line1, line2],
            organisation_name="Test Org",
            donor_name="Test Donor",
            exported_by="exporter@example.com",
            exported_at=datetime(2026, 9, 22, 14, 30, tzinfo=timezone.utc),
        )

        ws = load_workbook(io.BytesIO(data))["Original Budget"]
        rows = list(ws.iter_rows(values_only=True))

        # Header block; row 6 (Estimated Exchange Rate) is the formulas' rate cell ($B$6).
        # No extra_fields anywhere in this budget, so Amount/Estimate sit in B/C (no gap column).
        assert rows[0] == ("Organisation Name", "Test Org", None)
        assert rows[1] == ("Donor Name", "Test Donor", None)
        assert rows[2] == ("Project Name", budget.name, None)
        assert rows[4] == ("Estimated Currency", "USD", None)
        assert rows[5] == ("Estimated Exchange Rate", 2.0, None)

        # Budget Summary: title doubles as the column header row; each category
        # references its own Detailed Budget subtotal cell, not a recomputed value.
        assert rows[8] == ("BUDGET SUMMARY", "Amount (GBP)", "Estimate (USD)")
        assert rows[9] == ("Personnel", "=B17", "=C17")
        assert rows[10] == ("Travel", "=B21", "=C21")
        assert rows[11] == ("TOTAL", "=SUM(B10:B11)", "=SUM(C10:C11)")
        assert ws.cell(row=10, column=1).border.top.style == "thin"
        assert ws.cell(row=10, column=1).border.left.style == "thin"
        assert ws.cell(row=11, column=3).border.bottom.style == "thin"
        assert ws.cell(row=11, column=3).border.right.style == "thin"
        assert ws.cell(row=12, column=1).border.top.style is None

        # Detailed Budget: category header row (no repeated column headers), lines,
        # then a SUM-formula subtotal row so hand-edits to a line amount recalculate.
        assert rows[13] == ("DETAILED BUDGET", None, None)
        assert rows[14] == ("Personnel", None, None)
        assert rows[15] == ("Salaries", 1000.0, "=B16/$B$6")
        assert rows[16] == ("Subtotal", "=SUM(B16:B16)", "=SUM(C16:C16)")
        assert rows[18] == ("Travel", None, None)
        assert rows[19] == ("Flights", 200.0, "=B20/$B$6")
        assert rows[20] == ("Subtotal", "=SUM(B20:B20)", "=SUM(C20:C20)")

        assert ws.cell(row=16, column=1).border.top.style == "thin"
        assert ws.cell(row=16, column=1).border.left.style == "thin"
        assert ws.cell(row=16, column=3).border.top.style == "thin"
        assert ws.cell(row=16, column=3).border.right.style == "thin"
        assert ws.cell(row=16, column=1).border.bottom.style == "thin"
        assert ws.cell(row=20, column=1).border.top.style == "thin"
        assert ws.cell(row=20, column=1).border.bottom.style == "thin"

        # Footer: total expenditures sums each category's own subtotal cell.
        assert rows[23] == ("Total expenditures", "=B17+B21", "=C17+C21")
        assert rows[27] == ("Authorised Signatory", None, None)
        assert rows[31] == ("Project contact person", None, None)
        assert ws.cell(row=27, column=1).border.top.style == "thin"
        assert ws.cell(row=31, column=1).border.top.style == "thin"

        assert rows[33] == (
            "Generated by OpenGrantFlow · exporter@example.com · 2026-09-22 14:30 UTC",
            None,
            None,
        )
        assert ws.cell(row=34, column=1).font.italic is True

        total_expenditures_cell = ws.cell(row=24, column=1)
        assert total_expenditures_cell.font.bold is True
        assert total_expenditures_cell.fill.fgColor.rgb == "00D9D9D9"

        assert ws.column_dimensions["A"].width == 26.63
        assert ws.column_dimensions["B"].width == 17.77
        assert ws["B16"].number_format == '#,##0.00" GBP"'
        assert ws["C16"].number_format == '#,##0.00" USD"'

