async def _make_budget(db, owner_id=OWNER_ID, funding_customer_id=None):
    # Raw model, not BudgetFactory: setting its .budget relationship nulls the FK at flush.
    budget = BudgetModel(
        name="Test Budget",
        owner_id=owner_id,
        funding_customer_id=funding_customer_id,
        status=BudgetStatus.confirmed,
        start_date=date(2026, 1, 1),
        duration_months=12,
        local_currency="GBP",
    )
    db.add(budget)
    await db.commit()
    await db.refresh(budget)
    return budget


async def _make_category(db, budget_id, name="Personnel"):
    category = BudgetCategoryModel(budget_id=budget_id, name=name)
    db.add(category)
    await db.commit()
    await db.refresh(category)
    return category


async def _make_line(db, budget_id, category_id, amount=1000.0):
    line = BudgetLineModel(
        budget_id=budget_id, category_id=category_id, description="Salaries", amount=amount
    )
    db.add(line)
    await db.commit()
    await db.refresh(line)
    return line


@pytest.mark.anyio
class TestExportBudgetWorkbookRoute:
    async def test_owner_can_export(self, db, make_client):
        budget = await _make_budget(db)
        category = await _make_category(db, budget.id)
        await _make_line(db, budget.id, category.id)
        client = make_client(db=db, customer_id=OWNER_ID)

        with (
            patch(
                "app.services.excel_export_service.get_customer_cached",
                new_callable=AsyncMock,
                return_value={"name": "Test Org"},
            ),
            patch(
                "app.services.excel_export_service.get_users_by_ids_cached",
                new_callable=AsyncMock,
                return_value={},
            ),
        ):
            response = client.get(f"/api/v1/budgets/{budget.id}/export.xlsx")

        assert response.status_code == 200
        assert response.headers["content-type"] == (
            "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
        )
        wb = load_workbook(io.BytesIO(response.content))
        assert wb.sheetnames == ["Original Budget"]

    async def test_funder_can_export(self, db, make_client):
        budget = await _make_budget(db, funding_customer_id=FUNDER_ID)
        client = make_client(db=db, customer_id=FUNDER_ID)

        with (
            patch(
                "app.services.excel_export_service.get_customer_cached",
                new_callable=AsyncMock,
                return_value={"name": "Test Org"},
            ),
            patch(
                "app.services.excel_export_service.get_users_by_ids_cached",
                new_callable=AsyncMock,
                return_value={},
            ),
        ):
            response = client.get(f"/api/v1/budgets/{budget.id}/export.xlsx")

        assert response.status_code == 200

    async def test_stranger_is_rejected(self, db, make_client):
        budget = await _make_budget(db)
        client = make_client(db=db, customer_id=STRANGER_ID)

        response = client.get(f"/api/v1/budgets/{budget.id}/export.xlsx")

        assert response.status_code == 400
