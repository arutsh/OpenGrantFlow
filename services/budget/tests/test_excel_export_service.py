class TestPeriodLabel:
    def test_none_start_date_returns_none(self):
        assert _period_label(None, 12) is None

    def test_formats_start_and_computed_end_month(self):
        assert _period_label(date(2026, 1, 1), 12) == "01/2026-12/2026"

    def test_no_duration_shows_start_month_only(self):
        assert _period_label(date(2026, 3, 15), None) == "03/2026"

    def test_zero_duration_shows_start_month_only(self):
        """0 is BudgetModel.duration_months's column default — same "unknown" case as None."""
        assert _period_label(date(2026, 3, 15), 0) == "03/2026"


